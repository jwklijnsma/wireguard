package server

import (
	"fmt"
	"net"
	"net/netip"
	"strings"
)

// Export formats for a peer configuration.
const (
	FormatWGQuick  = "wgquick"
	FormatMikroTik = "mikrotik"
	FormatOpenWrt  = "openwrt"
	FormatOPNsense = "opnsense"
)

var exportFormats = []struct{ ID, Name, Ext string }{
	{FormatWGQuick, "wg-quick / WireGuard app (.conf)", "conf"},
	{FormatMikroTik, "MikroTik RouterOS 7 script", "rsc"},
	{FormatOpenWrt, "OpenWrt UCI commands", "sh"},
	{FormatOPNsense, "OPNsense / pfSense (values)", "txt"},
}

func renderConfig(format, name string, c clientConfig) (string, error) {
	priv := c.PrivateKey
	if priv == "" {
		priv = "<YOUR-PRIVATE-KEY>"
	}
	switch format {
	case FormatWGQuick, "":
		var b strings.Builder
		fmt.Fprintf(&b, "# %s — generated by wg2fa\n[Interface]\nPrivateKey = %s\nAddress = %s\n", name, priv, c.Address)
		if len(c.DNS) > 0 {
			fmt.Fprintf(&b, "DNS = %s\n", strings.Join(c.DNS, ", "))
		}
		if c.MTU > 0 {
			fmt.Fprintf(&b, "MTU = %d\n", c.MTU)
		}
		fmt.Fprintf(&b, "\n[Peer]\nPublicKey = %s\n", c.ServerPublicKey)
		if c.PresharedKey != "" {
			fmt.Fprintf(&b, "PresharedKey = %s\n", c.PresharedKey)
		}
		fmt.Fprintf(&b, "Endpoint = %s\nAllowedIPs = %s\n", c.Endpoint, strings.Join(c.AllowedIPs, ", "))
		if c.Keepalive > 0 {
			fmt.Fprintf(&b, "PersistentKeepalive = %d\n", c.Keepalive)
		}
		return b.String(), nil

	case FormatMikroTik:
		host, port, _ := net.SplitHostPort(c.Endpoint)
		iface := "wg2fa"
		var b strings.Builder
		fmt.Fprintf(&b, "# %s — RouterOS 7.x, paste into a terminal or /import\n", name)
		fmt.Fprintf(&b, "/interface wireguard add name=%s private-key=\"%s\" mtu=%d\n", iface, priv, c.MTU)
		fmt.Fprintf(&b, "/interface wireguard peers add interface=%s public-key=\"%s\" preshared-key=\"%s\" endpoint-address=%s endpoint-port=%s allowed-address=%s persistent-keepalive=%ds comment=\"wg2fa\"\n",
			iface, c.ServerPublicKey, c.PresharedKey, host, port, strings.Join(c.AllowedIPs, ","), c.Keepalive)
		fmt.Fprintf(&b, "/ip address add address=%s interface=%s\n", c.Address, iface)
		self, _ := netip.ParsePrefix(c.Address)
		for _, a := range c.AllowedIPs {
			if p, err := netip.ParsePrefix(a); a == "0.0.0.0/0" || (err == nil && p.Masked() == self.Masked()) {
				continue // default route needs policy routing; connected subnet is implicit
			}
			fmt.Fprintf(&b, "/ip route add dst-address=%s gateway=%s comment=\"wg2fa\"\n", a, iface)
		}
		fmt.Fprintf(&b, "/interface list member add list=LAN interface=%s\n", iface)
		return b.String(), nil

	case FormatOpenWrt:
		host, port, _ := net.SplitHostPort(c.Endpoint)
		var b strings.Builder
		fmt.Fprintf(&b, "#!/bin/sh\n# %s — OpenWrt 22.03+ (opkg install wireguard-tools luci-proto-wireguard)\n", name)
		fmt.Fprintf(&b, "uci set network.wg2fa=interface\nuci set network.wg2fa.proto='wireguard'\nuci set network.wg2fa.private_key='%s'\nuci add_list network.wg2fa.addresses='%s'\nuci set network.wg2fa.mtu='%d'\n", priv, c.Address, c.MTU)
		fmt.Fprintf(&b, "uci add network wireguard_wg2fa\nuci set network.@wireguard_wg2fa[-1].description='wg2fa'\nuci set network.@wireguard_wg2fa[-1].public_key='%s'\nuci set network.@wireguard_wg2fa[-1].preshared_key='%s'\nuci set network.@wireguard_wg2fa[-1].endpoint_host='%s'\nuci set network.@wireguard_wg2fa[-1].endpoint_port='%s'\nuci set network.@wireguard_wg2fa[-1].persistent_keepalive='%d'\nuci set network.@wireguard_wg2fa[-1].route_allowed_ips='1'\n",
			c.ServerPublicKey, c.PresharedKey, host, port, c.Keepalive)
		for _, a := range c.AllowedIPs {
			fmt.Fprintf(&b, "uci add_list network.@wireguard_wg2fa[-1].allowed_ips='%s'\n", a)
		}
		b.WriteString("uci add_list firewall.@zone[0].network='wg2fa'\nuci commit network\nuci commit firewall\n/etc/init.d/network reload\n")
		return b.String(), nil

	case FormatOPNsense:
		var b strings.Builder
		fmt.Fprintf(&b, "%s — VPN > WireGuard\n\nInstance (local)\n  Private key : %s\n  Tunnel addr : %s\n  MTU         : %d\n\nPeer (endpoint)\n  Public key  : %s\n  Shared key  : %s\n  Endpoint    : %s\n  Allowed IPs : %s\n  Keepalive   : %d\n",
			name, priv, c.Address, c.MTU, c.ServerPublicKey, c.PresharedKey, c.Endpoint, strings.Join(c.AllowedIPs, ", "), c.Keepalive)
		return b.String(), nil
	}
	return "", fmt.Errorf("unknown format %q", format)
}

func formatExt(format string) string {
	for _, f := range exportFormats {
		if f.ID == format {
			return f.Ext
		}
	}
	return "conf"
}
